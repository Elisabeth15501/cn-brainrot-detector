function countTerm(text, term) {
  if (/^[a-zA-Z]+$/.test(term)) { const re = new RegExp(term, "gi"); const mm = text.match(re); return mm ? mm.length : 0; }
  return text.split(term).length - 1;
}
function countEffective(text, d) {
  const base = countTerm(text, d.t); if (base === 0) return 0;
  const gMatch = (pats) => { let n = 0; for (const pat of pats) { const src = pat.source; const flags = pat.flags.includes("g") ? pat.flags : pat.flags + "g"; const mm = text.match(new RegExp(src, flags)); if (mm) n += mm.length; } return n; };
  if (d.only && d.only.length) return gMatch(d.only);
  if (!d.amb || !d.ex || d.ex.length === 0) return base;
  return Math.max(0, base - gMatch(d.ex));
}
function fullDetect(text) {
  const hits = [];
  for (const d of DICT) { const c = countEffective(text, d); if (c > 0) hits.push(d.t + "×" + c); }
  return hits;
}

